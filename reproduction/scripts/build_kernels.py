"""Build self-contained Kaggle script kernels: kaggle/<name>/{kernel.py, kernel-metadata.json}."""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
USER = os.environ.get("KAGGLE_USERNAME", "arnavd371")   # owner of the pushed kernels
MODULES = ["metnn_exp1.py", "metnn_instr.py", "run_all.py", "fisher_vs_rate.py"]

TEMPLATE = r'''# Auto-generated by build_kernels.py. Embeds the reproduction scripts verbatim.
import os, shutil, subprocess, sys
FILES = {files!r}
WORK = "/tmp/run"            # CIFAR download + scratch (kept out of /kaggle/working)
OUT = "/kaggle/working/results"
os.makedirs(WORK, exist_ok=True); os.makedirs(OUT, exist_ok=True)
for name, src in FILES.items():
    open(os.path.join(WORK, name), "w").write(src)
    open(os.path.join(OUT, name), "w").write(src)   # ship the exact code with results
for args in {jobs!r}:
    print(">>>", args, flush=True)
    rc = subprocess.run([sys.executable, "-u", *args, "--out", OUT], cwd=WORK).returncode
    print("<<< rc", rc, flush=True)
if os.path.isdir(os.path.join(WORK, "figures")):
    shutil.copytree(os.path.join(WORK, "figures"), os.path.join(OUT, "figures"), dirs_exist_ok=True)
'''

KERNELS = {
    "metnn-repro-smoke": [["run_all.py", "smoke"]],
    "metnn-repro-all": [["run_all.py", "part1"], ["run_all.py", "part2"], ["run_all.py", "part3"]],
    "metnn-svhn-fisher": [["fisher_vs_rate.py"], ["run_all.py", "svhn"]],
}


def build(name, jobs):
    d = os.path.join(ROOT, "kaggle", name); os.makedirs(d, exist_ok=True)
    files = {m: open(os.path.join(HERE, m)).read() for m in MODULES}
    open(os.path.join(d, "kernel.py"), "w").write(TEMPLATE.format(files=files, jobs=jobs))
    json.dump(dict(id=f"{USER}/{name}", title=name, code_file="kernel.py",
                   language="python", kernel_type="script", is_private=True,
                   enable_gpu=True, enable_internet=True, machine_shape="NvidiaTeslaT4",
                   dataset_sources=[], competition_sources=[], kernel_sources=[]),
              open(os.path.join(d, "kernel-metadata.json"), "w"), indent=1)
    print("built", d)


if __name__ == "__main__":
    for n in (sys.argv[1:] or KERNELS):
        build(n, KERNELS[n])
